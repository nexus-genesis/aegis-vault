#!/usr/bin/env node
/**
 * sync-deny-list.mjs — single-source generator for the Smart Account deny list.
 *
 * The JS semantic engine (packages/chain-eth/src/smart-account.js) owns the
 * canonical deny sets (SELF_ESCALATION_ACTIONS + ALLOWANCE_SURFACE_ACTIONS).
 * This script derives two artifacts from them so JS and Solidity can never
 * drift (the Sprint 2 gap that let allowance-surface variants bypass the
 * on-chain guard):
 *
 *   contracts/solidity/testdata/deny-actions.json  canonical fixture, also
 *     consumed by the Foundry suite to assert every entry is rejected
 *   contracts/solidity/src/DenyList.sol            generated Solidity library
 *
 * Usage:
 *   node scripts/sync-deny-list.mjs         # regenerate artifacts + verify
 *   node scripts/sync-deny-list.mjs --check # verify only; fail if drifted
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ALLOWANCE_SURFACE_ACTIONS,
  SELF_ESCALATION_ACTIONS,
  normalizeAction,
} from '../packages/chain-eth/src/smart-account.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const sorted = (arr) => [...new Set(arr)].sort();
const selfEsc = sorted([...SELF_ESCALATION_ACTIONS].map(normalizeAction));
const allowance = sorted([...ALLOWANCE_SURFACE_ACTIONS].map(normalizeAction));

// The on-chain deny check compares keccak256(normalized) against these exact
// literals. Guard against any entry that would produce a weaker/ambiguous
// normalized form (must be a non-empty lowercase ASCII word).
for (const e of [...selfEsc, ...allowance]) {
  if (!/^[a-z0-9]+$/.test(e)) {
    throw new Error(`refusing to generate deny list with non-normalized entry: "${e}"`);
  }
}

const denyJson = JSON.stringify(
  { self_escalation: selfEsc, allowance_surface: allowance },
  null,
  2,
) + '\n';

function denyFn(name, entries) {
  const ors = entries.map((e) => `            h == keccak256("${e}")`).join(' ||\n');
  return (
    `    /// @return true when \`h\` (keccak256 of a normalized string) is a ${name} action.\n` +
    `    function ${name}(bytes32 h) internal pure returns (bool) {\n` +
    `        if (\n${ors}\n        ) return true;\n` +
    `        return false;\n    }`
  );
}

const denylistSol =
`// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/**
 * @title DenyList — normalized deny list for the SmartAccount (GENERATED).
 * @notice GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * Single source of truth: contracts/solidity/testdata/deny-actions.json, itself
 * generated by scripts/sync-deny-list.mjs from the JS canonical sets
 * (packages/chain-eth/src/smart-account.js SELF_ESCALATION_ACTIONS /
 * ALLOWANCE_SURFACE_ACTIONS). The cross-language golden rule: the JS semantic
 * engine and the on-chain SmartAccount must reject the exact same surface, or
 * a variant that JS blocks will slip through on-chain.
 *
 * normalize() mirrors JS normalizeAction (strip whitespace/underscore/dash,
 * lowercase), so any casing/separator variant of a deny action is caught
 * on-chain (INV-005 self-escalation / INV-007 allowance surface).
 */
library DenyList {
    /// Strip whitespace, underscores and dashes; lowercase A-Z.
    /// Mirrors packages/chain-eth/src/smart-account.js normalizeAction.
    function normalize(string calldata value) internal pure returns (bytes memory out) {
        bytes memory b = bytes(value);
        out = new bytes(b.length);
        uint256 n = 0;
        for (uint256 i = 0; i < b.length; i++) {
            uint8 c = uint8(b[i]);
            if (c == 0x20 || c == 0x09 || c == 0x0a || c == 0x0d || c == 0x0b || c == 0x0c || c == 0x5f || c == 0x2d) continue;
            if (c >= 0x41 && c <= 0x5a) c += 0x20;
            out[n++] = bytes1(c);
        }
        assembly ("memory-safe") {
            mstore(out, n)
        }
    }

${denyFn('isSelfEscalation', selfEsc)}

${denyFn('isAllowanceSurface', allowance)}
}
`;

const jsonPath = join(ROOT, 'contracts/solidity/testdata/deny-actions.json');
const solPath = join(ROOT, 'contracts/solidity/src/DenyList.sol');

if (CHECK) {
  for (const [path, expected] of [[jsonPath, denyJson], [solPath, denylistSol]]) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      console.error(`[sync-deny-list] DRIFT: ${path} is out of sync with the JS deny sets.`);
      console.error('Run `node scripts/sync-deny-list.mjs` and commit the regenerated files.');
      process.exit(1);
    }
  }
  console.log(
    `[sync-deny-list] OK — JS sets, deny-actions.json and DenyList.sol are in sync ` +
    `(${selfEsc.length} self-escalation + ${allowance.length} allowance-surface).`,
  );
} else {
  writeFileSync(jsonPath, denyJson);
  writeFileSync(solPath, denylistSol);
  console.log(`[sync-deny-list] wrote ${jsonPath}`);
  console.log(`[sync-deny-list] wrote ${solPath}`);
  console.log(`[sync-deny-list] ${selfEsc.length} self-escalation + ${allowance.length} allowance-surface entries`);
}
